/**
 * Remix declares its icons with `children?: never`, so TypeScript won't accept them as Astryx's `IconType`
 * (an SVG component), although at runtime they are exactly that: function components that render an <svg>.
 */
const remix = (icon: typeof RiAddLine): IconType => icon as unknown as IconType;

